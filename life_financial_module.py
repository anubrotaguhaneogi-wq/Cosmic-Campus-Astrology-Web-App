def normalize_gender(gender):
    """বিভিন্ন লেখা (bn/en) থেকে 'female' বা 'male' বের করে।"""
    if gender is None:
        raise ValueError("লিঙ্গ (gender) দেওয়া আবশ্যক: 'female' বা 'male'")
    g = str(gender).strip().lower()
    if g in ("female", "f", "girl", "woman", "মেয়ে", "নারী", "মহিলা", "কন্যা"):
        return GENDER_FEMALE
    if g in ("male", "m", "boy", "man", "ছেলে", "পুরুষ", "পুত্র"):
        return GENDER_MALE
    raise ValueError(f"চেনা যায়নি: {gender!r} — 'female' বা 'male' ব্যবহার করুন")


def _phase_index_for_age(age: int) -> int:
    age = max(age, 1)
    for i, sk in enumerate(PHASE_SKELETON):
        start, end = sk["range"]
        if start <= age <= end:
            return i
    return len(PHASE_SKELETON) - 1


def get_phase_for_age(age: int, gender=GENDER_MALE):
    """বয়স ও লিঙ্গ অনুযায়ী পর্যায় (গ্রহ + জীবন + শরীর + অর্থনীতি) ফেরত দেয়।"""
    gender = normalize_gender(gender)
    i = _phase_index_for_age(age)
    sk = PHASE_SKELETON[i]
    c = PHASE_CONTENT[gender][i]
    return {
        "range": sk["range"],
        "planet": sk["planet"],
        "planet_en": sk["planet_en"],
        "life_progression": c["life"],
        "body": c["body"],
        "money": c["money"],
    }


def get_full_profile(age: int, gender):
    """বয়স ও লিঙ্গ অনুযায়ী সম্পূর্ণ প্রোফাইল ফেরত দেয় (পর্যায় + কৈশোর যদি প্রযোজ্য হয়)।"""
    phase = get_phase_for_age(age, gender)
